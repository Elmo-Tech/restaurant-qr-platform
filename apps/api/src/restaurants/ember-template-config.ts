/** Presentation-only config; default advertising copy is editable in every field. */
export const EMBER_PALETTES = ['EMBER', 'NOIR', 'COPPER'] as const;
export const EMBER_MOTIONS = ['SUBTLE', 'OFF'] as const;
export const EMBER_IMAGE_MODES = ['AUTO', 'CUSTOM'] as const;
export type EmberPalette = (typeof EMBER_PALETTES)[number];
export type EmberMotion = (typeof EMBER_MOTIONS)[number];
export type EmberImageMode = (typeof EMBER_IMAGE_MODES)[number];

export interface EmberTemplateSettings {
  palette: EmberPalette;
  motion: EmberMotion;
  navTaglineAr: string;
  navTaglineEn: string;
  eyebrowAr: string;
  eyebrowEn: string;
  headlineAr: string;
  headlineEn: string;
  subtitleAr: string;
  subtitleEn: string;
  signatureAr: string;
  signatureEn: string;
  marqueeAr: string;
  marqueeEn: string;
  heroImageMode: EmberImageMode;
  /** Set by our authenticated image-upload endpoint only, never a client URL. */
  heroImageAssetPath: string | null;
}


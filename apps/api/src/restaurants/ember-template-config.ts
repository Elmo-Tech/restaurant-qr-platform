/** Accept only paths generated by ImageStorageService's randomUUID storage. */
export function isStoredEmberHeroAssetPath(value: unknown): value is string {
  return typeof value === 'string' &&
    /^\/media\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(?:jpg|png|webp)$/.test(value);
}

/** Revalidates DB JSON, filling legacy empty/missing fields with visible defaults. */
export function normalizeEmberSettings(value: unknown): EmberTemplateSettings {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    return { ...DEFAULT_EMBER_SETTINGS };
  }
  const row = value as Record<string, unknown>;
  const text = (key: keyof EmberTemplateSettings, limit: number): string => {
    const input = row[key];
    const cleaned = typeof input === 'string' ? input.trim().slice(0, limit) : '';
    return cleaned || (DEFAULT_EMBER_SETTINGS[key] as string);
  };
  const asset = isStoredEmberHeroAssetPath(row.heroImageAssetPath) ? row.heroImageAssetPath : null;
  const mode = row.heroImageMode === 'CUSTOM' && asset ? 'CUSTOM' : 'AUTO';
  return {
    palette: EMBER_PALETTES.includes(row.palette as EmberPalette) ? row.palette as EmberPalette : 'EMBER',
    motion: EMBER_MOTIONS.includes(row.motion as EmberMotion) ? row.motion as EmberMotion : 'SUBTLE',
    navTaglineAr: text('navTaglineAr', 100),
    navTaglineEn: text('navTaglineEn', 100),
    eyebrowAr: text('eyebrowAr', 100),
    eyebrowEn: text('eyebrowEn', 100),
    headlineAr: text('headlineAr', 80),
    headlineEn: text('headlineEn', 80),
    subtitleAr: text('subtitleAr', 180),
    subtitleEn: text('subtitleEn', 180),
    signatureAr: text('signatureAr', 120),
    signatureEn: text('signatureEn', 120),
    marqueeAr: text('marqueeAr', 180),
    marqueeEn: text('marqueeEn', 180),
    heroImageMode: mode,
    heroImageAssetPath: asset,
  };
}
